export default function Layout() {
  const { user, tenant, logout, isAdmin } = useAuth();
  const navigate = useNavigate();

  const handleLogout = async () => {
    await logout();
    navigate('/login');
  };

  const navItems = [
    { to: '/dashboard', label: 'Dashboard', icon: 'dashboard' },
    { to: '/projects', label: 'Projects', icon: 'projects' },
    { to: '/analytics', label: 'Analytics', icon: 'analytics' },
    ...(isAdmin() ? [
      { to: '/users', label: 'Users', icon: 'users' },
      { to: '/billing', label: 'Billing & Invoices', icon: 'billing' },
      { to: '/accounting', label: 'Accounting', icon: 'accounting' },
    ] : []),
  ];

  const initials = user?.name?.split(' ').map(n => n[0]).join('').toUpperCase() || '?';

  return (
    <div className="app-layout">
      <aside className="sidebar">
        <div className="sidebar-logo">
          <h2>Construction<span>ERP</span></h2>
          <div className="sidebar-subtitle">{tenant?.name || 'Enterprise Platform'}</div>
        </div>

        <nav className="sidebar-nav">
          <div className="sidebar-section-label">Main Menu</div>
          {navItems.map(item => (
            <NavLink
              key={item.to}
              to={item.to}
              className={({ isActive }) => `nav-item${isActive ? ' active' : ''}`}
            >
              {icons[item.icon]}
              {item.label}
            </NavLink>
          ))}
        </nav>

        <div className="sidebar-footer">
          <div className="user-card">
            <div className="user-avatar">{initials}</div>
            <div className="user-info">
              <div className="user-name">{user?.name}</div>
              <div className="user-role">{user?.role?.replace('_', ' ')}</div>
            </div>
          </div>
          <button
            className="nav-item"
            onClick={handleLogout}
            style={{ width: '100%', marginTop: 8, background: 'none', border: 'none' }}
          >
            {icons.logout}
            Sign Out
          </button>
        </div>
      </aside>

      <main className="main-content">
        <Outlet />
      </main>
    </div>
  );
}
